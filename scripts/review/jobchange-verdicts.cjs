// 爻辞只翻一次，按定稿第十三节第 3 步（READING_POLICY_V2 256–257 行），在「有条件按结局拆」之后：
//   降档之辞落在去上，凡判成之篇：克体在变用；或体死而有克体之卦有力；或盘中根本无克体之卦（无克可阻，凶辞直接主断）——合一条即翻为不成；
//   不合的，凶辞作要过的坎，成而先准备。
//   升档之辞，凡判不成之篇：至少一处生体之卦旺相，体不囚死，变用克体时另有限制（克体之卦不旺相而体旺相，或克体之卦死）；
//   无生有克（R3）的盘不升，初判为不成档的另须本用不克体（第二步「难升为有条件：本用不克体」）。合则翻为成，成而先准备。
function lineFlip(t, done, fx, key) {
  const a = adjust(fx), q = k => a.n[k].slice(-1), bq = fx.n.body.slice(-1);
  const G = P4.filter(k => fx.rel[k] === 'use_generates_body'), K = P4.filter(k => fx.rel[k] === 'use_controls_body');
  if (LINE_DOWN[key] && done === 'F') {
    const hit = K.includes('changed_use') ? '克体在变用' : (bq === '死' && K.some(k => strong(q(k)))) ? '体死而克体之卦有力' : !K.length ? '盘中无克体之卦，凶辞直接主断' : null;
    return hit ? {done:'D', note:'爻辞翻为不成（' + hit + '）：' + LINE_DOWN[key], down:true} : {done, note:'爻辞作要过的坎：' + LINE_DOWN[key], down:true};
  }
  if (LINE_UP[key] && done === 'D') {
    const end = fx.rel.changed_use;
    const ok = G.some(k => strong(q(k))) && bq !== '囚' && bq !== '死' && !/^R3/.test(t.why) && (t.t !== 'D' || fx.rel.use !== 'use_controls_body')
      && (end !== 'use_controls_body' || (!strong(q('changed_use')) && strong(bq)) || q('changed_use') === '死');
    if (ok) return {done:'F', note:'爻辞翻为成：' + LINE_UP[key], up:true};
  }
  return {done, note:''};
}
function jobChangeOf(fx, hexId, changedId, line) {
  const key = hexId + '-' + line;
  const t0 = tierFinal(fx, hexId, changedId, false, {useParty:true}); // 用党多则体势衰（用户 2026-11-19 定）
  const K = P4.filter(k => fx.rel[k] === 'use_controls_body');
  const done0 = split(t0, fx, 'end');
  const s = lineFlip(t0, done0, fx, key);
  let v, why = t0.why + (t0.t === 'C' ? ' → 有条件按结局拆为' + (done0 === 'F' ? '成' : '不成') : '') + (s.note ? ' → ' + s.note : '');
  if (s.done === 'D') v = 'stay';
  else if (t0.t === 'F' && !K.length && !s.down && !s.up && (fx.rel.use === 'use_generates_body' || fx.rel.use === 'equal') && !LINE_WAIT[key]) { v = 'switch'; why += fx.rel.use === 'equal' ? ' → 本用比和，求谋称意' : ' → 本用生体，不谋而成、即成'; }
  else {
    v = 'prepare';
    if (!s.down && !s.up) why += t0.t === 'C' ? ' → 事有阻节' : K.length ? ' → 有克体之卦，事有阻节' : LINE_WAIT[key] ? ' → 爻辞待时：' + LINE_WAIT[key]
      : fx.rel.use === 'body_controls_use' ? ' → 本用体克用，谋虽可成，但成迟' : fx.rel.use === 'body_generates_use' ? ' → 本用泄而后得生，稍迟' : ' → 成而稍迟';
  }
  return {v, tier:t0.t, split:done0, final:s.done, why, K};
}
